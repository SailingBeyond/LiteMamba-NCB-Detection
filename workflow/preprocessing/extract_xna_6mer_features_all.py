#!/usr/bin/env python3
# -*- coding: utf-8 -*-

import argparse
import csv
import os
import sys
from collections import Counter

import numpy as np

COMP_TABLE_XY = str.maketrans({
    "A": "T", "C": "G", "G": "C", "T": "A", "N": "N", "X": "Y", "Y": "X",
    "a": "t", "c": "g", "g": "c", "t": "a", "n": "n", "x": "y", "y": "x",
})


def revcomp_xy(seq: str) -> str:
    return seq.translate(COMP_TABLE_XY)[::-1]


def robust_mad_scale(arr: np.ndarray, use_unique: bool = True, eps: float = 1e-8):
    if arr.size == 0:
        return None, None
    base = np.unique(arr) if use_unique else arr
    if base.size == 0:
        return None, None
    center = float(np.median(base))
    mad = float(np.median(np.abs(base - center)) * 1.4826)
    if (not np.isfinite(mad)) or mad < eps:
        std = float(np.std(base))
        if np.isfinite(std) and std >= eps:
            mad = std
        else:
            mad = 1.0
    return center, mad


def fmt_num(x, ndigits=6):
    s = f"{float(x):.{ndigits}f}"
    s = s.rstrip("0").rstrip(".")
    return s if s else "0"


def compute_kmer_ref_window(target_pos: int, strand: str):
    """
    返回参考序列坐标系(1-based, inclusive)下应截取的 6mer 窗口，
    使得“目标位点”在最终输出的 5'->3' 6mer 中都是第4个碱基。

    正链：
        取 [target-3, target+2]
        输出后 target 是第4个碱基

    负链：
        在参考正向坐标上取 [target-2, target+3]
        然后做 reverse-complement，并把各特征顺序逆置
        最终输出 5'->3' 时，target 是第4个碱基
    """
    if strand == "+":
        return target_pos - 3, target_pos + 2
    if strand == "-":
        return target_pos - 2, target_pos + 3
    raise ValueError(f"Unsupported strand: {strand}")


def mask_center_base(seq: str, masked_base: str = "N", center_index_0based: int = 3) -> str:
    if len(seq) != 6:
        raise ValueError(f"Expected 6mer, got length={len(seq)}")
    return seq[:center_index_0based] + masked_base + seq[center_index_0based + 1:]


def parse_args():
    p = argparse.ArgumentParser(
        description=(
            "Streamingly extract strand-aware 6mer features from the large TSV generated by "
            "extract_signal_from_fast5_XY.py. "
            "The target site is fixed to be the 4th base of the output 6mer. "
            "The output kmer will have its 4th base masked to N. "
            "Labels: X=4, Y=5."
        )
    )
    p.add_argument("--input", required=True, help="Input TSV from extract_signal_from_fast5_XY.py")
    p.add_argument("--output", required=True, help="Output feature CSV")
    p.add_argument("--meta_out", default=None, help="Optional metadata TSV for traceability")

    # 新规则相关参数
    p.add_argument("--target_pos", type=int, default=1275,
                   help="Target base position on the reference positive strand (1-based). Default: 1275")
    p.add_argument("--min_left_pos", type=int, default=1258,
                   help="Require row_start <= this position to ensure enough barcode coverage. Default: 1258")
    p.add_argument("--mask_base", default="N",
                   help="Mask the 4th base of output 6mer with this base. Default: N")
    p.add_argument("--label_x", type=int, default=4,
                   help="Label assigned to X on the positive strand. Default: 4")
    p.add_argument("--label_y", type=int, default=5,
                   help="Label assigned to Y on the negative strand. Default: 5")

    # 保留旧参数名以避免你旧命令直接报错，但这些参数现在不参与新规则筛选
    p.add_argument("--barcode_start", type=int, default=None,
                   help="[legacy, ignored] no longer used in the new rule")
    p.add_argument("--barcode_end", type=int, default=None,
                   help="[legacy, ignored] no longer used in the new rule")
    p.add_argument("--barcode_min_cover", type=int, default=None,
                   help="[legacy, ignored] no longer used in the new rule")
    p.add_argument("--max_ref_index", type=int, default=None,
                   help="[legacy, ignored] no longer used in the new rule")

    p.add_argument("--dwell_scale", type=float, default=1.0,
                   help="Output dwell as len(segment)/dwell_scale. Default: 1.0")
    p.add_argument("--quality_scale", type=float, default=1.0,
                   help="Output quality as Q/quality_scale. Default: 1.0")
    p.add_argument("--mad_use_unique", type=int, choices=[0, 1], default=1,
                   help="Use unique full-read signal values for median-MAD scaling. Default: 1")
    p.add_argument("--require_strand_match", type=int, choices=[0, 1], default=1,
                   help="Skip rows whose bam_strand != tombo_strand. Default: 1")
    p.add_argument("--with_header", action="store_true", help="Write CSV header")
    p.add_argument("--signal_round", type=int, default=6, help="Decimal places for normalized raw signal. Default: 6")
    p.add_argument("--stat_round", type=int, default=6, help="Decimal places for summary statistics. Default: 6")
    p.add_argument("--log_every", type=int, default=100000, help="Log progress every N input rows. Default: 100000")
    return p.parse_args()


def main():
    args = parse_args()
    stats = Counter()

    out_dir = os.path.dirname(os.path.abspath(args.output))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    if args.meta_out:
        meta_dir = os.path.dirname(os.path.abspath(args.meta_out))
        if meta_dir:
            os.makedirs(meta_dir, exist_ok=True)

    with open(args.input, "r", encoding="utf-8", buffering=1024 * 1024 * 16) as fin, \
         open(args.output, "w", newline="", encoding="utf-8", buffering=1024 * 1024 * 16) as fout:

        writer = csv.writer(fout)

        meta_fp = None
        meta_writer = None
        if args.meta_out:
            meta_fp = open(args.meta_out, "w", encoding="utf-8", buffering=1024 * 1024 * 8)
            meta_writer = csv.writer(meta_fp, delimiter="\t")
            meta_writer.writerow([
                "read_id",
                "chrom",
                "bam_strand",
                "tombo_strand",
                "strand_match",
                "row_start",
                "row_end",
                "target_pos",
                "kmer_ref_start",
                "kmer_ref_end",
                "raw_oriented_6mer",
                "masked_6mer",
                "true_base",
                "label",
            ])

        try:
            if args.with_header:
                writer.writerow([
                    "kmer",
                    "mean",
                    "std",
                    "median",
                    "dwell",
                    "quality",
                    "mismatch",
                    "insertion",
                    "deletion",
                    "signal",
                    "label",
                ])

            for line_no, line in enumerate(fin, start=1):
                if line_no == 1 and line.startswith("read_id\t"):
                    stats["header_skipped"] += 1
                    continue

                stats["rows_total"] += 1
                if args.log_every > 0 and stats["rows_total"] % args.log_every == 0:
                    print(
                        f"[progress] rows={stats['rows_total']:,} kept={stats['rows_written']:,} "
                        f"bad={stats['bad_rows']:,} filtered={stats['rows_filtered']:,}",
                        file=sys.stderr,
                        flush=True,
                    )

                parts = line.rstrip("\n").split("\t")
                if len(parts) < 12:
                    stats["bad_rows"] += 1
                    stats["bad_tsv_field_count"] += 1
                    continue

                read_id = parts[0]
                chrom = parts[1]

                try:
                    row_start = int(parts[2])
                except Exception:
                    stats["bad_rows"] += 1
                    stats["bad_start"] += 1
                    continue

                ref_seq_full = parts[3]
                if not ref_seq_full:
                    stats["bad_rows"] += 1
                    stats["empty_ref_seq"] += 1
                    continue

                qual_s = parts[4]
                bam_strand = parts[5]
                tombo_strand = parts[6]
                strand_match = parts[7]
                signal_s = parts[8]
                mismatch_s = parts[9]
                insertion_s = parts[10]
                deletion_s = parts[11]

                if args.require_strand_match and strand_match != "1":
                    stats["rows_filtered"] += 1
                    stats["skip_strand_mismatch"] += 1
                    continue

                if bam_strand not in ("+", "-"):
                    stats["bad_rows"] += 1
                    stats["bad_bam_strand"] += 1
                    continue

                row_end = row_start + len(ref_seq_full) - 1

                # 新的最低覆盖要求：read 左端必须到达 1258 位或更靠左
                if row_start > args.min_left_pos:
                    stats["rows_filtered"] += 1
                    stats["skip_left_not_enough"] += 1
                    continue

                try:
                    kmer_ref_start, kmer_ref_end = compute_kmer_ref_window(args.target_pos, bam_strand)
                except Exception:
                    stats["bad_rows"] += 1
                    stats["bad_target_window"] += 1
                    continue

                # 至少要完整覆盖用于提取 6mer 的窗口
                if not (row_start <= kmer_ref_start and row_end >= kmer_ref_end):
                    stats["rows_filtered"] += 1
                    stats["skip_kmer_not_fully_covered"] += 1
                    continue

                left = kmer_ref_start - row_start
                right = kmer_ref_end - row_start + 1
                if left < 0 or right > len(ref_seq_full) or (right - left) != 6:
                    stats["bad_rows"] += 1
                    stats["bad_window_indices"] += 1
                    continue

                ref_seq_win = ref_seq_full[left:right]
                qual_list = qual_s.split("|")
                mismatch_list = mismatch_s.split("|")
                insertion_list = insertion_s.split("|")
                deletion_list = deletion_s.split("|")
                signal_list = signal_s.split("|")

                full_len = len(ref_seq_full)
                if not (
                    len(qual_list) == full_len and
                    len(mismatch_list) == full_len and
                    len(insertion_list) == full_len and
                    len(deletion_list) == full_len and
                    len(signal_list) == full_len
                ):
                    stats["bad_rows"] += 1
                    stats["bad_field_length_inconsistent"] += 1
                    continue

                qual_win = qual_list[left:right]
                mismatch_win = mismatch_list[left:right]
                insertion_win = insertion_list[left:right]
                deletion_win = deletion_list[left:right]
                signal_win = signal_list[left:right]

                # 统一输出成 5'->3'
                if bam_strand == "-":
                    ref_seq_win = revcomp_xy(ref_seq_win)
                    qual_win = qual_win[::-1]
                    mismatch_win = mismatch_win[::-1]
                    insertion_win = insertion_win[::-1]
                    deletion_win = deletion_win[::-1]
                    signal_win = signal_win[::-1]

                ref_seq_win = ref_seq_win.upper()

                # 真实标签按“链方向”判定：
                # + 链视为中心真实碱基 X
                # - 链视为中心真实碱基 Y
                if bam_strand == "+":
                    true_base = "X"
                    label = args.label_x
                else:
                    true_base = "Y"
                    label = args.label_y

                # 为了模型训练，强制把输出 6mer 的第4位掩蔽成 N
                try:
                    masked_kmer = mask_center_base(ref_seq_win, masked_base=args.mask_base, center_index_0based=3)
                except Exception:
                    stats["bad_rows"] += 1
                    stats["bad_mask_center"] += 1
                    continue

                flat_signal = np.fromstring(signal_s.replace("|", "*"), sep="*", dtype=np.float32)
                if flat_signal.size == 0:
                    stats["bad_rows"] += 1
                    stats["empty_signal"] += 1
                    continue

                center, scale = robust_mad_scale(flat_signal, use_unique=bool(args.mad_use_unique))
                if center is None or scale is None:
                    stats["bad_rows"] += 1
                    stats["bad_mmad"] += 1
                    continue

                means = []
                stds = []
                medians = []
                dwells = []
                raw_norm_segments = []

                ok = True
                for seg_str in signal_win:
                    seg = np.fromstring(seg_str, sep="*", dtype=np.float32)
                    if seg.size == 0:
                        ok = False
                        break

                    seg = (seg - center) / scale
                    means.append(fmt_num(np.round(np.mean(seg), args.stat_round), args.stat_round))
                    stds.append(fmt_num(np.round(np.std(seg), args.stat_round), args.stat_round))
                    medians.append(fmt_num(np.round(np.median(seg), args.stat_round), args.stat_round))
                    dwells.append(fmt_num(np.round(seg.size / args.dwell_scale, args.stat_round), args.stat_round))
                    raw_norm_segments.append("*".join(fmt_num(v, args.signal_round) for v in seg))

                if not ok or len(raw_norm_segments) != 6:
                    stats["bad_rows"] += 1
                    stats["bad_signal_segment"] += 1
                    continue

                try:
                    qual_out = [
                        fmt_num(np.round(float(x) / args.quality_scale, args.stat_round), args.stat_round)
                        for x in qual_win
                    ]
                    mismatch_out = [
                        fmt_num(np.round(float(x), args.stat_round), args.stat_round)
                        for x in mismatch_win
                    ]
                    insertion_out = [
                        fmt_num(np.round(float(x), args.stat_round), args.stat_round)
                        for x in insertion_win
                    ]
                    deletion_out = [
                        fmt_num(np.round(float(x), args.stat_round), args.stat_round)
                        for x in deletion_win
                    ]
                except Exception:
                    stats["bad_rows"] += 1
                    stats["bad_numeric_field"] += 1
                    continue

                writer.writerow([
                    masked_kmer,
                    "|".join(means),
                    "|".join(stds),
                    "|".join(medians),
                    "|".join(dwells),
                    "|".join(qual_out),
                    "|".join(mismatch_out),
                    "|".join(insertion_out),
                    "|".join(deletion_out),
                    "|".join(raw_norm_segments),
                    label,
                ])
                stats["rows_written"] += 1
                stats[f"label_{label}"] += 1
                stats[f"strand_{bam_strand}"] += 1

                if meta_writer is not None:
                    meta_writer.writerow([
                        read_id,
                        chrom,
                        bam_strand,
                        tombo_strand,
                        strand_match,
                        row_start,
                        row_end,
                        args.target_pos,
                        kmer_ref_start,
                        kmer_ref_end,
                        ref_seq_win,
                        masked_kmer,
                        true_base,
                        label,
                    ])

        finally:
            if meta_fp is not None:
                meta_fp.close()

    print("\n[Summary]", file=sys.stderr)
    for k in sorted(stats):
        print(f"{k}: {stats[k]}", file=sys.stderr)


if __name__ == "__main__":
    main()